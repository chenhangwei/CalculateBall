def checkbox_tip(name, prefix):
    key = _key_of(name, prefix)
    if key.startswith("checkBox_"):
        key = key[len("checkBox_"):]
    key = key[len(prefix):] if key.startswith(prefix) else key
    if key.endswith("Enable"):
        key = key[:-len("Enable")]
    if key in ROPE_NAMES:
        return f"勾选后，{ROPE_NAMES[key]}计入重量清单。"
    if key == "PullPoint":
        return "勾选后，拉点计入重量清单并参与拉点载荷校核。"
    if key in EQUIPMENT:
        return f"勾选后，{EQUIPMENT[key]}计入重量清单。"
    return None


def apply_tips(ui, page, prefix):
    """给页面上全部输入/输出控件、所在行的标签与单位设置悬停提示；返回缺少提示的对象名。"""
    from ui_layout import find_item  # 避免循环导入

    missing = []
    for attribute, value in list(vars(ui).items()):
        if isinstance(value, (QLineEdit, QComboBox, QCheckBox, QTextEdit)) and not value.objectName():
            value.setObjectName(attribute)
    for widget in page.findChildren((QLineEdit, QComboBox, QCheckBox, QTextEdit)):
        name = widget.objectName()
        if not name:
            continue
        if isinstance(widget, QCheckBox):
            tip = checkbox_tip(name, prefix)
        else:
            tip = tip_for(name, prefix)
        if tip is None:
            missing.append(name)
            continue
        if isinstance(widget, QLineEdit) and not widget.isReadOnly():
            key = _key_of(name, prefix)
            if key in REQUIRED_KEYS or (key == "Diameter" and prefix == "Sphere"):
                tip += "\n【必填】橙色框为必须输入的关键参数。"
        text = _html(tip)
        widget.setToolTip(text)
        found = find_item(page.layout(), widget)
        if found:
            row = found[0]
            for index in range(row.count()):
                label = row.itemAt(index).widget()
                if isinstance(label, QLabel):
                    label.setToolTip(text)
    for radio_name, tip in (("radio_NoSail", "不加帆：只有囊体本体承受风载。"),
                            ("radio_PocketSail", "兜帆：在囊体上加兜形帆，增加气动升力，同时增加风阻。"),
                            ("radio_WingSail", "翼帆：加碳纤维杆撑开的翼形帆，升力系数更高。")):
        radio = getattr(ui, radio_name, None)
        if isinstance(radio, QRadioButton) and prefix == "Sphere":
            radio.setToolTip(_html(tip))
    return missing
